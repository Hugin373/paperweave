// Copies the pdf.js worker that matches the installed react-pdf version into /public,
// so the browser can load it from the app's own origin. The legacy build works on older browsers too
// (see the resolveAlias note in next.config.ts).
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
try {
  const reactPdfDir = path.dirname(require.resolve("react-pdf/package.json"));
  const workerPath = require.resolve("pdfjs-dist/legacy/build/pdf.worker.min.mjs", { paths: [reactPdfDir] });
  mkdirSync("public", { recursive: true });
  copyFileSync(workerPath, path.join("public", "pdf.worker.min.mjs"));
  // The worker's entry: Safari (as of 26.3) cannot loop over streams with `for await`, which pdf.js's worker
  // does when unpacking compressed PDF data, so a fallback is added before the worker loads.
  writeFileSync(
    path.join("public", "pdf.worker.entry.mjs"),
    `// Generated by scripts/copy-pdf-worker.mjs.
if (typeof ReadableStream !== "undefined" && !ReadableStream.prototype[Symbol.asyncIterator]) {
  ReadableStream.prototype[Symbol.asyncIterator] = async function* () {
    const reader = this.getReader();
    try {
      for (;;) {
        const { done, value } = await reader.read();
        if (done) return;
        yield value;
      }
    } finally {
      reader.releaseLock();
    }
  };
}
await import("./pdf.worker.min.mjs");
`,
  );
} catch (err) {
  if (existsSync("node_modules/react-pdf")) throw err;
}
